// Writes test/coverage_helper_test.dart, a test that imports every library
// under lib/.
//
// `flutter test --coverage` records only the libraries some test loads, so a
// file no test imports - a new screen, a use case nobody tested - was simply
// absent from lcov.info: the total coverage and every per-layer figure stayed
// where they were, and the floor in ci.yml could not notice an untested file.
// Importing everything makes each one appear, with zero hits where nothing
// ran.
//
// Run it before `flutter test --coverage` (ci.yml, coverage.yml and
// scripts/test/test_coverage.sh do). The output is git-ignored.
//
// Usage: dart run tool/coverage_helper.dart [output path]

import 'dart:io';

const _defaultOutput = 'test/coverage_helper_test.dart';

void main(List<String> args) {
  final output = args.isEmpty ? _defaultOutput : args.single;
  // Read, not hard-coded: the setup brick renames the package.
  final packageName = RegExp(
    r'^name:\s*(\S+)',
    multiLine: true,
  ).firstMatch(File('pubspec.yaml').readAsStringSync())!.group(1);
  final libraries =
      Directory('lib')
          .listSync(recursive: true)
          .whereType<File>()
          .map((f) => f.path.replaceAll(r'\', '/'))
          .where(
            (path) =>
                path.endsWith('.dart') &&
                !path.endsWith('.g.dart') &&
                !path.endsWith('.freezed.dart'),
          )
          // A part file is not a library and cannot be imported; its owner
          // brings it in.
          .where(
            (path) => !File(path).readAsLinesSync().any(
              (l) => l.startsWith('part of'),
            ),
          )
          .toList()
        ..sort();
  // The generated test runs on the VM, where a library importing a web-only
  // library does not load - and one such import failed the whole test step.
  // Those are left out (a conditional import stays in: it loads its VM side).
  final webOnly = libraries.where(isWebOnlyLibrary).toList();
  libraries.removeWhere(webOnly.contains);

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/coverage_helper.dart - do not edit.')
    ..writeln(
      '// Imports every library under lib/ so `flutter test --coverage`',
    )
    ..writeln('// records the untested ones too, with zero hits.')
    ..writeln('// ignore_for_file: unused_import, directives_ordering')
    ..writeAll([
      for (final path in webOnly)
        '// Left out, web-only (does not load on the VM): $path\n',
    ])
    ..writeln()
    ..writeln("import 'package:flutter_test/flutter_test.dart';");
  for (final (i, path) in libraries.indexed) {
    final uri = 'package:$packageName/${path.substring('lib/'.length)}';
    // Prefixed, so two libraries declaring the same name do not clash.
    buffer.writeln("import '$uri' as l$i;");
  }
  buffer
    ..writeln()
    ..writeln('void main() {')
    ..writeln("  test('every library under lib/ loads', () {")
    ..writeln(
      '    // no-assertion-ok: must not throw - loading every library is the '
      'whole',
    )
    ..writeln('    // contract; coverage reads what ran, not an expectation.')
    ..writeln('  });')
    ..writeln('}');

  File(output).writeAsStringSync(buffer.toString());
  // Formatted, so the format check over test/ (pre-commit, CI) accepts it
  // while it sits in the tree.
  Process.runSync('dart', ['format', output]);
  stdout.writeln('Wrote $output (${libraries.length} libraries).');
}

/// Imports or exports of a library that exists only on the web. An export
/// loads the library just as an import does.
final RegExp _webOnlyImport = RegExp(
  r'''^\s*(?:import|export)\s+['"](dart:(html|js|js_util|js_interop|js_interop_unsafe|ui_web|indexed_db|web_gl|web_audio|svg)['"]|package:web/)''',
  multiLine: true,
);

/// Whether the library at [path] imports or exports a web-only library
/// directly.
bool isWebOnlyLibrary(String path) =>
    _webOnlyImport.hasMatch(File(path).readAsStringSync());
